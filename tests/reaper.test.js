import { test } from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { createCatalog, macroPatch, validatePatch, verifyReadback } from '../src/lib/reaper-catalog.js';
import { toLua } from '../scripts/gen-jsfx-sliders.js';
import { SYNTH_PARAMS } from '../src/dsp/params.js';

const catalog = createCatalog();
test('automation catalog is generated reproducibly, with unambiguous slider and API indices', () => {
  assert.deepEqual(JSON.parse(readFileSync(new URL('../jsfx/generated/automation.json', import.meta.url))), catalog);
  assert.equal(readFileSync(new URL('../jsfx/generated/catalog.lua', import.meta.url), 'utf8'),
    '-- Generated by npm run gen:jsfx. Do not edit.\nreturn ' + toLua(catalog) + '\n');
  const cutoff = catalog.instruments.synth.parameters.find((d) => d.id === 'filter_cutoff_hz');
  assert.equal(cutoff.slider, 19);
  assert.equal(cutoff.paramIndex, 18);
  assert.equal(cutoff.valueDomain, 'real');
  assert.deepEqual(catalog.instruments.synth.parameters.find((d) => d.id === 'voice_mode').enumValues,
    [{ value: 0, label: 'Poly' }, { value: 1, label: 'Mono' }, { value: 2, label: 'Legato' }]);
});

test('every catalog preset is in range, uses real units and preserves tuning', () => {
  for (const inst of Object.values(catalog.instruments)) {
    for (const p of inst.presets) {
      assert.ok(Object.keys(p.params).every((id) => !id.startsWith('tuning_')));
      const writes = validatePatch(inst, p.params);
      assert.ok(writes.every((w) => w.normalized >= 0 && w.normalized <= 1));
    }
  }
});

test('650 Hz is explicit in both value domains; normalized-as-real mistakes fail readback', () => {
  const inst = catalog.instruments.synth, params = { filter_cutoff_hz: 650 };
  const [write] = validatePatch(inst, params);
  assert.equal(write.value, 650);
  assert.equal(write.normalized, (650 - 20) / (20000 - 20));
  assert.deepEqual(verifyReadback(inst, params, { filter_cutoff_hz: 650 }), []);
  assert.equal(verifyReadback(inst, params, { filter_cutoff_hz: 20 }).length, 1);
  assert.equal(verifyReadback(inst, params, {}).length, 1);
  for (const params of [{ filter_cutoff_hz: write.normalized }, { voice_mode: 0.4 }, { voice_count: 9 },
    { filter_cutoff_hz: NaN }, { typo: 10 }]) assert.throws(() => validatePatch(inst, params));
});

test('macros touch only their declared targets, remain valid, and expose Duck explicitly', () => {
  const inst = catalog.instruments.synth;
  for (const macro of inst.macros) {
    for (const amount of [0, 0.25, 0.5, 0.75, 1]) {
      const patch = macroPatch(inst, macro.name, amount);
      validatePatch(inst, patch);
      assert.deepEqual(Object.keys(patch), macro.targets.map((t) => t.id));
      assert.ok(Object.keys(patch).every((id) => SYNTH_PARAMS.some((d) => d.id === id)));
    }
  }
  assert.deepEqual(macroPatch(inst, 'Pump', 0.7), { lfo_waveform: 5, lfo_sync: 7, lfo_amp: 0.7 });
  assert.throws(() => macroPatch(inst, 'Width', 2));
  assert.throws(() => macroPatch(inst, 'Width', NaN));
});
