// Keep native module IDs, port names, knob ranges and factory patches in sync with Web.
import { writeFileSync } from 'node:fs';
import {
  MODULAR_LINE_SAMPLES, MODULAR_LINES, MODULAR_MACROS, MODULAR_MATERIALS, MODULAR_MAX_INPUTS, MODULAR_MAX_OUTPUTS,
  MODULAR_MAX_PARAMS, MODULAR_MODAL_FIELDS, MODULAR_MODES, MODULAR_PATCH_BYTES, MODULAR_POSITION_MAX, MODULAR_PRESETS, MODULAR_TYPES,
} from '../src/dsp/modular.js';

const json = JSON.stringify;
const list = values => '{' + values.map(x => json(x)).join(', ') + '}';
const specs = Object.entries(MODULAR_TYPES).map(([type, spec]) => {
  const params = Object.entries(spec.params);
  // The native engine stores each module's ports and knobs in fixed arrays.
  if (spec.inputs.length > MODULAR_MAX_INPUTS || spec.outputs.length > MODULAR_MAX_OUTPUTS ||
      params.length > MODULAR_MAX_PARAMS) throw new Error(`Module ${type} exceeds the native port or knob limits`);
  const knobs = params.map(([name, p]) => `{${json(name)}, ${p.min}, ${p.max}, ${p.default}, ${p.step >= 1}, ${!!p.fixed}}`);
  return `    {Type::${type}, ${json(type)}, ${list(spec.inputs)}, ${list(spec.outputs)}, {${knobs.join(', ')}}},`;
});
const materials = MODULAR_MATERIALS.map(m => {
  if (m.ratios.length !== MODULAR_MODES || m.gains.length !== MODULAR_MODES) throw new Error(`Material ${m.name} needs ${MODULAR_MODES} modes`);
  return `    {{${m.ratios.join(', ')}}, {${m.gains.join(', ')}}}, // ${m.name}`;
});
const presets = MODULAR_PRESETS.map(p => `    {${json(p.name)}, ${json(json(p.patch()))}},`);
writeFileSync(process.argv[2], `// Generated by scripts/gen-modular-clap.js.
enum class Type { ${Object.keys(MODULAR_TYPES).join(', ')} };
constexpr size_t kMacroCount = ${MODULAR_MACROS};
constexpr size_t kPatchBytes = ${MODULAR_PATCH_BYTES};
constexpr double kPositionMax = ${MODULAR_POSITION_MAX};
constexpr size_t kMaxInputs = ${MODULAR_MAX_INPUTS}, kMaxParams = ${MODULAR_MAX_PARAMS}, kMaxOutputs = ${MODULAR_MAX_OUTPUTS};
constexpr size_t kLines = ${MODULAR_LINES}, kLineSamples = ${MODULAR_LINE_SAMPLES}, kModes = ${MODULAR_MODES};
${Object.entries(MODULAR_MODAL_FIELDS).map(([key, { min, max }]) => {
  const field = key[0].toUpperCase() + key.slice(1);
  return `constexpr double kModal${field}Min = ${min}, kModal${field}Max = ${max};`;
}).join('\n')}
const Spec kSpecs[] = {
${specs.join('\n')}
};
const Material kMaterials[] = {
${materials.join('\n')}
};
const Preset kPresets[] = {
${presets.join('\n')}
};
`);
