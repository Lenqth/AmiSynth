// Generate JSFX slider declarations + a JSON manifest from src/dsp/params.js.
//   node scripts/gen-jsfx-sliders.js
// Output goes to jsfx/generated/. Paste the slider block into the .jsfx file;
// the variable names are identical to the ids used by the JS DSP code.

import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { DRUM_PARAMS, PHYS_PARAMS, SYNTH_PARAMS, TUNING_HOLDER_PARAMS } from '../src/dsp/params.js';
import { resolvePreset } from '../src/lib/presets.js';
import { DRUM_PRESETS } from '../src/presets/drums.js';
import { SYNTH_PRESETS } from '../src/presets/synth.js';
import { PHYS_PRESETS } from '../src/presets/phys.js';
import { createCatalog } from '../src/lib/reaper-catalog.js';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const outDir = join(root, 'jsfx', 'generated');
export const LUA_CATALOG_HEADER = [
  '-- @description AmiSynth catalog: generated data library; dofile dependency, not an executable action.',
  '-- @about Returns parameter ranges/units/enums, preset values and macros as a Lua table. Running via script_run makes no project change and publishes no MCP result. Used by ../reaper/toolkit.lua; to design a sound from MCP run AmiSynth - Read sound.lua / AmiSynth - Apply sound.lua instead, and inspect automation.json or run AmiSynth - MCP guide.lua for usage. Regenerate with npm run gen:jsfx; do not edit by hand.',
  '-- Generated by npm run gen:jsfx. Do not edit.',
].join('\n') + '\n';

const num = (v) => String(Number(v.toFixed(6)));

/** @param {import('../src/dsp/params.js').ParamDef} d */
export function sliderLine(index, d) {
  // file chooser: no variable name (the code reads it as sliderN), value = index of the file
  if (d.file) return `slider${index}:${d.file.dir}:${d.file.default}:${d.name}`;
  // No ':log' shape on purpose: REAPER reports shaped sliders to the API / automation in the
  // shaped (ln) domain, so MCP tools would have to write ln(1800) instead of 1800. Plain sliders
  // take the real value (Hz, ms, ...). The web UI still turns 'log' params with a log knob.
  let range = `${num(d.min)},${num(d.max)},${num(d.step)}`;
  if (d.options) range += `{${d.options.join(',')}}`;
  const label = d.unit && !d.options ? `${d.name} [${d.unit}]` : d.name;
  return `slider${index}:${d.id}=${num(d.default)}<${range}>${label}`;
}

function block(title, defs) {
  const lines = [`// ${title} — generated by scripts/gen-jsfx-sliders.js from src/dsp/params.js. Do not edit by hand.`];
  defs.forEach((d, i) => lines.push(sliderLine(i + 1, d)));
  return lines.join('\n') + '\n';
}

/** JSFX instrument files whose slider block is generated from params.js */
export const JSFX_FILES = [
  ['AmiSynth Synth.jsfx', SYNTH_PARAMS],
  ['AmiSynth Drums.jsfx', DRUM_PARAMS],
  ['AmiSynth Physical.jsfx', PHYS_PARAMS],
  ['AmiSynth Tuning.jsfx', TUNING_HOLDER_PARAMS],
];

const BEGIN = '// <generated sliders>';
const END = '// </generated sliders>';

/** Replace the slider block between the markers; returns the new text. */
export function withSliders(text, defs) {
  const a = text.indexOf(BEGIN);
  const b = text.indexOf(END);
  if (a < 0 || b < a) throw new Error('generated slider markers not found');
  const lines = defs.map((d, i) => sliderLine(i + 1, d));
  return text.slice(0, a) + BEGIN + '\n' + lines.join('\n') + '\n' + text.slice(b);
}

/** REAPER factory preset libraries, installed next to the JSFX as `<file>.rpl` */
export const RPL_FILES = [
  ['AmiSynth Synth.jsfx', SYNTH_PARAMS, SYNTH_PRESETS],
  ['AmiSynth Physical.jsfx', PHYS_PARAMS, PHYS_PRESETS],
  ['AmiSynth Drums.jsfx', DRUM_PARAMS, DRUM_PRESETS],
];

/** Sliders a preset leaves alone: the track's tuning and file choosers ('-' in the preset). */
export const rplSkips = (d) => !!d.file || d.id.startsWith('tuning_');

/** Menu name of a built-in preset in REAPER's preset list (flat, so the category goes first). */
export const rplPresetName = (p) => (p.category && p.category !== 'Kit' ? `${p.category}: ${p.name}` : p.name);

/**
 * One preset as REAPER stores a JSFX state: sliders 1-64 ('-' = leave as is), the preset name,
 * sliders 65-256, then NUL and the @serialize data (none here). Base64, 128 chars per line.
 */
export function rplPresetBlob(defs, values, name) {
  const tok = (i) => (i < defs.length && !rplSkips(defs[i]) ? num(values[i]) : '-');
  const head = Array.from({ length: 64 }, (_, i) => tok(i));
  const tail = Array.from({ length: 192 }, (_, i) => tok(i + 64));
  const text = [...head, `\`${name}\``, ...tail].join(' ') + '\0';
  const b64 = Buffer.from(text, 'utf8').toString('base64');
  const lines = [];
  for (let i = 0; i < b64.length; i += 128) lines.push('    ' + b64.slice(i, i + 128));
  return lines.join('\n');
}

/** Whole `.rpl` text for one instrument. */
export function rplText(file, defs, presets) {
  const out = [`<REAPER_PRESET_LIBRARY \`JS: AmiSynth/${file}\``];
  for (const p of presets) {
    const name = rplPresetName(p);
    if (/[`\n]/.test(name)) throw new Error(`preset name not allowed in .rpl: ${name}`);
    const values = resolvePreset(defs, p);
    out.push(`  <PRESET \`${name}\``, rplPresetBlob(defs, defs.map((d) => values[d.id]), name), '  >');
  }
  out.push('>');
  return out.join('\n') + '\n';
}

function main() {
  mkdirSync(outDir, { recursive: true });
  writeFileSync(join(outDir, 'synth-sliders.txt'), block('AmiSynth Synth', SYNTH_PARAMS));
  writeFileSync(join(outDir, 'drums-sliders.txt'), block('AmiSynth Drums', DRUM_PARAMS));
  writeFileSync(join(outDir, 'phys-sliders.txt'), block('AmiSynth Physical', PHYS_PARAMS));
  writeFileSync(join(outDir, 'tuning-sliders.txt'), block('AmiSynth Tuning', TUNING_HOLDER_PARAMS));
  writeFileSync(join(outDir, 'params.json'), JSON.stringify({ synth: SYNTH_PARAMS, phys: PHYS_PARAMS, drums: DRUM_PARAMS, tuning: TUNING_HOLDER_PARAMS }, null, 2) + '\n');
  const catalog = createCatalog();
  writeFileSync(join(outDir, 'automation.json'), JSON.stringify(catalog, null, 2) + '\n');
  writeFileSync(join(outDir, 'catalog.lua'), LUA_CATALOG_HEADER + 'return ' + toLua(catalog) + '\n');
  // Full slider values per preset, in slider order (for building REAPER .rpl presets later).
  const resolved = (defs, presets) =>
    presets.map((p) => ({ name: p.name, category: p.category, description: p.description, sliders: defs.map((d) => resolvePreset(defs, p)[d.id]) }));
  writeFileSync(
    join(outDir, 'presets.json'),
    JSON.stringify({ synth: resolved(SYNTH_PARAMS, SYNTH_PRESETS), phys: resolved(PHYS_PARAMS, PHYS_PRESETS), drums: resolved(DRUM_PARAMS, DRUM_PRESETS) }, null, 1) + '\n',
  );
  for (const [file, defs, presets] of RPL_FILES) writeFileSync(join(root, 'jsfx', `${file}.rpl`), rplText(file, defs, presets));
  for (const [file, defs] of JSFX_FILES) {
    const path = join(root, 'jsfx', file);
    if (!existsSync(path)) continue;
    const text = readFileSync(path, 'utf8');
    const next = withSliders(text, defs);
    if (next !== text) writeFileSync(path, next);
  }
  console.log(`wrote ${SYNTH_PARAMS.length} synth + ${PHYS_PARAMS.length} physical + ${DRUM_PARAMS.length} drum sliders to jsfx/generated/`);
}

// Data only; no JSON parser or third-party Lua extension required by the companion.
export function toLua(value) {
  if (Array.isArray(value)) return '{' + value.map(toLua).join(',') + '}';
  if (value && typeof value === 'object') return '{' + Object.entries(value)
    .filter(([, v]) => v !== undefined)
    .map(([k, v]) => `[${toLua(k)}]=${toLua(v)}`).join(',') + '}';
  if (typeof value === 'string') return '"' + value.replace(/\\/g, '\\\\').replace(/"/g, '\\"').replace(/\n/g, '\\n').replace(/\r/g, '\\r') + '"';
  return String(value);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) main();
